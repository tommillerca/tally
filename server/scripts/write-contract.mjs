// Source-derived SQL write contract. No migration or schema.sql column list.
import { parse } from 'acorn';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const DYNAMIC = '__DYNAMIC_SQL__';
const ident = /^[a-z_][a-z0-9_]*$/i;

function textOf(node) {
  if (node.type === 'Literal' && typeof node.value === 'string') return node.value;
  if (node.type === 'TemplateLiteral') return node.quasis.map(q => q.value.cooked).join(DYNAMIC);
  if (node.type === 'BinaryExpression' && node.operator === '+') {
    return (textOf(node.left) ?? DYNAMIC) + (textOf(node.right) ?? DYNAMIC);
  }
  return null;
}

// SQL literals, comments and nested expressions must not masquerade as SET
// targets. Quoted identifiers are supported; computed identifiers fail closed.
function tokens(sql) {
  return [...sql.matchAll(/--[^\n]*|\/\*[\s\S]*?\*\/|'(?:''|[^'])*'|"(?:""|[^"])*"|`[^`]*`|\[[^\]]*\]|[a-z_][a-z0-9_]*|\S/gi)]
    .map(m => m[0]).filter(t => !t.startsWith('--') && !t.startsWith('/*'))
    .map(t => /^["`\[]/.test(t) ? t.slice(1, -1) : t);
}

export function deriveWrites(source, filename = 'source') {
  const ast = parse(source, { ecmaVersion: 'latest', sourceType: 'module', locations: true });
  const tables = {};
  function sqlWrite(sql, node) {
    const t = tokens(sql);
    const upper = t.map(s => s.toUpperCase());
    const fail = () => { throw new Error(`${filename}:${node.loc.start.line}: unsupported write SQL; use literal table and column names`); };
    if (!['INSERT', 'UPDATE', 'REPLACE'].includes(upper[0])) {
      // A CTE or a second statement must never hide a write from this parser.
      if (['WITH', 'SELECT', 'DELETE', DYNAMIC].includes(upper[0])
          && upper.some(t => ['INSERT', 'UPDATE', 'REPLACE'].includes(t))) fail();
      return;
    }
    if (t.indexOf(';') !== -1 && t.indexOf(';') !== t.length - 1) fail();
    let i = 1;
    if (upper[i] === 'OR') i += 2;
    if (upper[i] === 'INTO') i++;
    const table = t[i++];
    if (!ident.test(table || '') || table === DYNAMIC) fail();
    const columns = tables[table] ??= new Set();
    const add = col => {
      if (!ident.test(col || '') || col === DYNAMIC) fail();
      columns.add(col);
    };
    function assignments(start) {
      let depth = 0, target = true;
      for (let j = start; j < t.length; j++) {
        if (depth === 0 && ['WHERE', 'RETURNING', ';'].includes(upper[j])) break;
        if (target) {
          add(t[j]);
          if (t[j + 1] !== '=') fail();
          target = false;
          j++;
        } else if (t[j] === '(') depth++;
        else if (t[j] === ')') depth--;
        else if (t[j] === ',' && depth === 0) target = true;
      }
      if (target) fail();
    }
    if (upper[0] === 'UPDATE') {
      if (upper[i++] !== 'SET') fail();
      assignments(i);
    } else {
      if (t[i++] !== '(') fail(); // INSERT without explicit columns is unsafe.
      do {
        add(t[i++]);
        if (t[i] === ')') break;
        if (t[i++] !== ',') fail();
      } while (i < t.length);
      if (t[i] !== ')') fail();
      for (; i < t.length; i++) {
        if (upper[i] === 'DO' && upper[i + 1] === 'UPDATE' && upper[i + 2] === 'SET') {
          assignments(i + 3);
          break;
        }
      }
    }
  }
  function walk(node) {
    if (!node || typeof node !== 'object') return;
    const value = textOf(node);
    if (value !== null) {
      sqlWrite(value, node);
      // Also inspect interpolated expressions for nested SQL literals.
      if (node.type === 'TemplateLiteral') node.expressions.forEach(walk);
      return;
    }
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) value.forEach(walk);
      else if (value && typeof value === 'object') walk(value);
    }
  }
  walk(ast);
  return Object.fromEntries(Object.entries(tables).map(([t, c]) => [t, [...c].sort()]));
}

export function sourceContract(root) {
  const tables = {};
  function scan(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const file = join(dir, entry.name);
      if (entry.isDirectory()) scan(file);
      else if (/\.(m?js)$/.test(entry.name) && file !== join(root, 'write-contract.generated.js')) {
        for (const [table, columns] of Object.entries(deriveWrites(readFileSync(file, 'utf8'), file))) {
          const set = tables[table] ??= new Set();
          columns.forEach(c => set.add(c));
        }
      }
    }
  }
  scan(root);
  if (!Object.keys(tables).length) throw new Error('No SQL writes found; refusing an empty contract');
  return Object.fromEntries(Object.keys(tables).sort().map(t => [t, [...tables[t]].sort()]));
}

export function generatedSource(contract) {
  return '// Generated by node scripts/schema-guard.mjs --generate. Do not hand edit.\n'
    + `export const WRITE_COLUMNS = ${JSON.stringify(contract, null, 2)};\n`
    + 'export const WRITE_PROBES = Object.entries(WRITE_COLUMNS).map(([table, columns]) => ({\n'
    + '  table, sql: `UPDATE ${table} SET ${columns.map(c => `${c}=${c}`).join(",")} WHERE 0`,\n'
    + '}));\n';
}
